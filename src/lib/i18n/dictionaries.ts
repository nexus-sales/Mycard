export const dictionaries: Record<Locale, Dictionary> = { es, en };

/**
 * Los esquemas Zod devuelven claves (p. ej. "slugMin"). Esta función las traduce y
 * devuelve un mensaje genérico para cualquier mensaje por defecto de Zod en inglés.
 */
export function translateValidation(t: Dictionary, message: string | undefined): string {
  if (message && message in t.validation) {
    return t.validation[message as keyof Dictionary["validation"]];
  }
  return t.validation.generic;
}

export function translateFieldErrors(
  t: Dictionary,
  fieldErrors: Record<string, string[] | undefined>
): Record<string, string[]> {
  const result: Record<string, string[]> = {};
  for (const [field, messages] of Object.entries(fieldErrors)) {
    if (messages) result[field] = messages.map((m) => translateValidation(t, m));
  }
  return result;
}
